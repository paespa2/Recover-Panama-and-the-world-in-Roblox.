local function generateSectorRegions(
	prefix: string,
	sectorNames: { string },
	rivals: { string },
	difficultyStars: number
): { RegionNode }
	local list: { RegionNode } = {}
	local baseEnemyTroops = 75 + difficultyStars * 28

	for i, g in ipairs(PLANETARY_GRID) do
		local id = string.format("%s_%02d", prefix, i)
		local nIds: { string } = {}
		for _, nIdx in ipairs(g.neighbors) do
			table.insert(nIds, string.format("%s_%02d", prefix, nIdx))
		end

		local owner = "NEUTRAL"
		local troops = 55 + difficultyStars * 15
		local building: string? = nil

		if i == 3 or i == 6 then
			-- Bases iniciales del jugador (Panamá / Alianza)
			owner = "PANAMA"
			troops = if i == 6 then 210 else 145
			building = if i == 6 then "City" else "ResearchLab"
		elseif i % 2 == 1 then
			local rivalIdx = ((i - 1) % #rivals) + 1
			owner = rivals[rivalIdx]
			troops = baseEnemyTroops + (i * 6)
			if i == 1 or i == 13 then
				building = "Fortress"
			elseif i == 9 or i == 11 then
				building = "Barracks"
			end
		elseif i == 14 then
			owner = rivals[1]
			troops = baseEnemyTroops + 45
			building = "MissileSilo"
		end

		local shape = SHAPE_LIST[((i - 1) % #SHAPE_LIST) + 1]
		table.insert(list, {
			id = id,
			name = sectorNames[i] or ("Sector " .. tostring(i)),
			x = g.x,
			y = g.y,
			width = 74,
			height = 58,
			terrain = "plains",
			initialOwner = owner,
			initialTroops = troops,
			initialBuilding = building,
			goldBonus = 16 + (i % 4) * 5,
			oilBonus = 6 + (i % 3) * 4,
			neighbors = nIds,
			pixelShape = shape,
		})
	end

	return list
end

